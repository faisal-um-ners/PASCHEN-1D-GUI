#!/usr/bin/env bash
# Build a double-clickable "PASCHEN-1D Studio.app" inside the studio folder (macOS).
# The app simply starts the studio with the private virtual environment (studio/.venv).
set -euo pipefail
STUDIO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$STUDIO_DIR/PASCHEN-1D Studio.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$STUDIO_DIR/paschen_studio/gui/assets/paschen_studio.icns" "$APP/Contents/Resources/paschen_studio.icns"
VERSION=$(sed -n 's/^__version__ = "\(.*\)"/\1/p' "$STUDIO_DIR/paschen_studio/__init__.py")
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>PASCHEN-1D Studio</string>
  <key>CFBundleDisplayName</key><string>PASCHEN-1D Studio</string>
  <key>CFBundleIdentifier</key><string>edu.umich.paschen1d.studio</string>
  <key>CFBundleVersion</key><string>${VERSION}</string>
  <key>CFBundleShortVersionString</key><string>${VERSION}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>PASCHEN-1D Studio</string>
  <key>CFBundleIconFile</key><string>paschen_studio.icns</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
</dict>
</plist>
PLIST
cat > "$APP/Contents/MacOS/PASCHEN-1D Studio" <<LAUNCH
#!/bin/bash
# Launcher generated by make_macos_app.sh
HERE="\$(cd "\$(dirname "\$0")/../../.." && pwd)"
STUDIO_DIR="\$HERE"
[ -f "\$STUDIO_DIR/pyproject.toml" ] || STUDIO_DIR="$STUDIO_DIR"
PY="\$STUDIO_DIR/.venv/bin/python"
if [ ! -x "\$PY" ]; then
  open -a Terminal "\$STUDIO_DIR/Launch PASCHEN-1D Studio.command"
  exit 0
fi
cd "\$STUDIO_DIR"
exec "\$PY" -m paschen_studio gui "\$@"
LAUNCH
chmod +x "$APP/Contents/MacOS/PASCHEN-1D Studio"
touch "$APP"
echo "$APP"
